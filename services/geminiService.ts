export async function generateLongTailKeywords(keyword: string): Promise<string[]> {
    const prompt = `围绕核心关键词 "${keyword}"，生成20个与生产制造相关的长尾关键词。
要求：
1.  每个长尾关键词都必须包含核心关键词 "${keyword}"。
2.  每个长尾关键词都应包含类似 "厂家"、"供应商"、"公司" 或 "制造商" 这样的词语，使其更侧重于B2B搜索意图。
3.  输出为纯文本列表，每个关键词占一行，不要添加数字、破折号或任何其他格式。`;
    const response = await ai.models.generateContent({
        model: 'gemini-2.5-flash',
        contents: prompt,
    });
    const text = response.text;
    return text.split('\n').map(kw => kw.trim()).filter(kw => kw.length > 0);
}

export async function generateTopics(keywords: string[], year: string): Promise<string[]> {
    const keywordsString = keywords.join(', ');
    const prompts = [
        `基于关键词 "${keywordsString}"，生成20个吸引人的文章选题。
要求：
1.  每个选题必须融入 "厂家"、"供应商"、"制造商" 或 "公司" 这类词语。
2.  选题中必须巧妙地包含以下至少一个概念：排名比较 (如：前十, 前三, top 10), 推荐, 地理区域 (用 [地名] 作为占位符), 哪家好, 口碑, 联系方式。
3.  输出为纯文本列表，每个选题占一行，不要添加任何额外格式。`,
    ];
    
    if (year) {
        prompts.push(`另外，请专门为年份 "${year}" 生成3个与关键词 "${keywordsString}" 相关的选题。
要求：
1. 选题必须明确包含年份 "${year}"。
2. 每个选题必须融入 "厂家"、"供应商"、"制造商" 或 "公司" 这类词语。
3. 输出为纯文本列表，每个选题占一行，不要添加任何额外格式。`);
    }

    const response = await ai.models.generateContent({
        model: 'gemini-2.5-flash',
        contents: prompts.join('\n\n---\n\n'),
    });
    const text = response.text;
    return text.split('\n').map(topic => topic.trim()).filter(topic => topic.length > 0 && !topic.startsWith('--'));
}

